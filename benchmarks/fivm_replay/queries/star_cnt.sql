IMPORT DTREE FROM FILE 'star_cnt.order';

CREATE STREAM G1(A INT, B INT) FROM FILE 'unused.g1' LINE DELIMITED CSV;
CREATE STREAM G2(A INT, C INT) FROM FILE 'unused.g2' LINE DELIMITED CSV;
CREATE STREAM G3(A INT, D INT) FROM FILE 'unused.g3' LINE DELIMITED CSV;
CREATE STREAM G4(A INT, E INT) FROM FILE 'unused.g4' LINE DELIMITED CSV;

SELECT A, SUM(1)
FROM G1 NATURAL JOIN G2 NATURAL JOIN G3 NATURAL JOIN G4
GROUP BY A;
